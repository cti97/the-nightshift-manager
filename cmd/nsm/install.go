// installSpec is what an install writes down: how to start this agent, and where its secret lives.
//
// The token is deliberately NOT in the unit file or the plist. Both are world-readable on most
// systems and are copied into logs and backups by everything that touches a service directory; a
// node credential in a unit file is a credential in every backup of that machine. The unit runs a
// small wrapper that reads an environment file written 0600, and the wrapper is the only thing that
// knows the token exists.
type installSpec struct {
	Binary  string   // absolute path to the nsm binary
	NodeID  string   // --node
	Args    []string // the rest of `agent run`'s flags, already validated by parseAgentConfig
	Token   string   // NSM_NODE_TOKEN at install time; written to the env file, never to a unit
	BaseDir string   // ~/.config/nsm on both platforms, ~/.local/share/nsm on Windows
	Label   string   // launchd label / systemd unit name
}

const installLabel = "com.nightshift.agent"

func (s installSpec) envPath() string     { return filepath.Join(s.BaseDir, "agent.env") }
func (s installSpec) wrapperPath() string { return filepath.Join(s.BaseDir, "agent-run.sh") }

// wrapperScript is what the service manager actually runs. `exec env -i` is not used: the agent
// needs PATH to find /bin/sh for its shell tool, and the sandbox builds children's environments
// separately anyway. The token is exported from the file and never appears on a command line.
func (s installSpec) wrapperScript() string {
	quoted := make([]string, 0, len(s.Args)+1)
	quoted = append(quoted, shellQuote(s.Binary), "agent", "run")
	for _, a := range s.Args {
		quoted = append(quoted, shellQuote(a))
	}
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by `nsm agent install`. Edit the flags by re-running it, not by hand.\n")
	b.WriteString("set -eu\n")
	b.WriteString(". \"" + s.envPath() + "\"\n")
	b.WriteString("export NSM_NODE_TOKEN\n")
	b.WriteString("exec " + strings.Join(quoted, " ") + "\n")
	return b.String()
}

// launchdPlist is the macOS unit. KeepAlive restarts the agent after a crash; RunAtLoad starts it
// at login. ThrottleInterval keeps a crash loop from becoming a fork bomb.
func (s installSpec) launchdPlist() string {
	esc := func(v string) string {
		var b strings.Builder
		_ = xml.EscapeText(&b, []byte(v))
		return b.String()
	}
	args := []string{s.wrapperPath()}
	var argXML strings.Builder
	for _, a := range args {
		argXML.WriteString("    <string>" + esc(a) + "</string>\n")
	}
	return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>` + esc(s.Label) + `</string>
  <key>ProgramArguments</key>
  <array>
` + argXML.String() + `  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>30</integer>
  <key>StandardOutPath</key><string>` + esc(filepath.Join(s.BaseDir, "agent.log")) + `</string>
  <key>StandardErrorPath</key><string>` + esc(filepath.Join(s.BaseDir, "agent.err")) + `</string>
</dict>
</plist>
`
}

// systemdUnit is the Linux unit: a user unit, because the agent needs no root and a system unit
// would run as root with the user's model keys — the opposite of least privilege. Restart=always
// with a start limit is launchd's KeepAlive and throttle in systemd's spelling.
func (s installSpec) systemdUnit() string {
	return `[Unit]
Description=The Night Shift Manager agent
After=network-online.target

[Service]
Type=simple
ExecStart=` + s.wrapperPath() + `
Restart=always
RestartSec=30
StartLimitIntervalSec=300
StartLimitBurst=5

[Install]
WantedBy=default.target
`
}

// installFiles is every file an install writes, keyed by path, in the order they should be written
// (env and wrapper first: a unit pointing at a missing wrapper is a broken service).
func (s installSpec) installFiles() ([]struct {
	Path string
	Body string
	Mode os.FileMode
}, error) {
	if s.Token == "" {
		return nil, fmt.Errorf("NSM_NODE_TOKEN is required at install time: the service reads it from %s", s.envPath())
	}
	if strings.ContainsAny(s.Token, "\n\r\"'\\") {
		// The env file is sourced by a shell. A token with a quote or a newline would either break
		// the source or, worse, inject a line the shell would run.
		return nil, fmt.Errorf("NSM_NODE_TOKEN contains a character that cannot go in an environment file")
	}
	env := "# Generated by `nsm agent install`; mode 0600, read by the wrapper, never by a unit file.\n" +
		"NSM_NODE_TOKEN=" + shellQuote(strings.TrimSpace(s.Token)) + "\n"
	files := []struct {
		Path string
		Body string
		Mode os.FileMode
	}{
		{s.envPath(), env, 0o600},
		{s.wrapperPath(), s.wrapperScript(), 0o700},
	}
	switch runtime.GOOS {
	case "darwin":
		home, err := os.UserHomeDir()
		if err != nil {
			return nil, err
		}
		files = append(files, struct {
			Path string
			Body string
			Mode os.FileMode
		}{filepath.Join(home, "Library", "LaunchAgents", s.Label+".plist"), s.launchdPlist(), 0o644})
	case "linux":
		files = append(files, struct {
			Path string
			Body string
			Mode os.FileMode
		}{filepath.Join(s.BaseDir, s.Label+".service"), s.systemdUnit(), 0o644})
	default:
		return nil, fmt.Errorf("no service manager is generated for %s yet; --print shows what would be written on darwin or linux", runtime.GOOS)
	}
	return files, nil
}

// shellQuote quotes one argument for /bin/sh. Only plain words are left bare, so a path with a
// space, a quote or a dollar survives the wrapper.
func shellQuote(s string) string {
	if s == "" {
		return "''"
	}
	plain := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case strings.ContainsRune("/._-:=,@%+", r):
		default:
			plain = false
		}
	}
	if plain {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// installCommand is `nsm agent install`: write the service files, and load them unless --print.
//
// The flags are validated by parseAgentConfig — the same validator the running agent uses, so an
// install cannot produce a service that fails at its first start for a reason the CLI already knows
// how to explain.
func installCommand(args []string, out, errOut io.Writer) int {
	fs := flag.NewFlagSet("agent install", flag.ContinueOnError)
	fs.SetOutput(errOut)
	baseURL := fs.String("board", defaultBoard, "board base URL")
	nodeID := fs.String("node", "", "node id, as registered with the board (required)")
	provides := fs.String("provides", "", "comma-separated live capabilities")
	reach := fs.String("reach", "", "comma-separated reach classes")
	sandboxRoot := fs.String("sandbox-root", "", "absolute path under which each run gets a disposable directory (required)")
	policyPath := fs.String("policy", "", "JSON file of per-tool verdicts (allow|deny|ask)")
	executorKind := fs.String("executor", "agentic", "agentic, reflex or command")
	runCmd := fs.String("run-cmd", "", "with --executor command: the harness command line")
	harnessName := fs.String("harness", "", "with --executor command: the harness name, declared as harness:<name>")
	printOnly := fs.Bool("print", false, "print the files instead of writing them")
	upgrade := fs.Bool("upgrade", false, "replace this binary with the release the board serves first (needs NSM_ADMIN_TOKEN)")
	pubKey := fs.String("pubkey", os.Getenv("NSM_RELEASE_PUBKEY"), "base64 ed25519 release key to pin (or a file holding it)")
	if err := fs.Parse(args); err != nil {
		return 2
	}

	// Read the token before validating: parseAgentConfig consumes and unsecures it, exactly as the
	// running agent does, and the env file being written needs the value.
	token := os.Getenv("NSM_NODE_TOKEN")

	runArgs := []string{"--board", *baseURL, "--node", *nodeID,
		"--provides", *provides, "--reach", *reach,
		"--sandbox-root", *sandboxRoot, "--executor", *executorKind}
	if *policyPath != "" {
		runArgs = append(runArgs, "--policy", *policyPath)
	}
	// The command executor's flags must be written into the unit too. Without this, `install
	// --executor command` wrote a service whose first start failed with "--executor command needs
	// --run-cmd" — a unit that could never run, discovered at 3am by a reboot rather than here.
	if *runCmd != "" {
		runArgs = append(runArgs, "--run-cmd", *runCmd)
	}
	if *harnessName != "" {
		runArgs = append(runArgs, "--harness", *harnessName)
	}
	if _, ok := parseAgentConfig(runArgs, errOut); !ok {
		return 2
	}

	home, err := os.UserHomeDir()
	if err != nil {
		fmt.Fprintf(errOut, "install: %v\n", err)
		return 1
	}
	bin, err := os.Executable()
	if err != nil {
		fmt.Fprintf(errOut, "install: cannot find this binary's path: %v\n", err)
		return 1
	}
	if resolved, lerr := filepath.EvalSymlinks(bin); lerr == nil {
		bin = resolved
	}
	spec := installSpec{
		Binary:  bin,
		NodeID:  *nodeID,
		Args:    runArgs,
		Token:   token,
		BaseDir: filepath.Join(home, ".config", "nsm"),
		Label:   installLabel,
	}
	if *upgrade && *printOnly {
		// --print exists so an operator can look before anything changes. An upgrade replaces the
		// binary, so the combination has no meaning that is not a surprise.
		fmt.Fprintln(errOut, "install: --print and --upgrade cannot be combined: printing must not replace the binary")
		return 2
	}
	if *upgrade {
		if *pubKey == "" {
			// Without a pinned key an upgrade is a shell script from the internet with a checksum
			// attached by whoever served it.
			fmt.Fprintln(errOut, "install: --upgrade needs --pubkey (the key the release was signed with)")
			return 2
		}
		// The installed release is recorded beside the env file: it is the only record of what this
		// node is running, and the anti-rollback rule needs it to refuse an older signed release.
		recordPath := filepath.Join(spec.BaseDir, "installed-release")
		installed, _ := os.ReadFile(recordPath)
		guard := func(entry release.Entry) error {
			return refuseDowngrade(strings.TrimSpace(string(installed)), entry)
		}
		entry, err := upgradeFromBoard(context.Background(), *baseURL, os.Getenv("NSM_ADMIN_TOKEN"), *pubKey, bin, guard, out)
		if err != nil {
			fmt.Fprintf(errOut, "install: upgrade: %v\n", err)
			return 1
		}
		if err := os.MkdirAll(spec.BaseDir, 0o700); err != nil {
			fmt.Fprintf(errOut, "install: %v\n", err)
			return 1
		}
		if err := os.WriteFile(recordPath, []byte(entry.File+"\n"), 0o600); err != nil {
			fmt.Fprintf(errOut, "install: record the installed release: %v\n", err)
			return 1
		}
	}
	files, err := spec.installFiles()
	if err != nil {
		fmt.Fprintf(errOut, "install: %v\n", err)
		return 2
	}
	if *printOnly {
		for _, f := range files {
			fmt.Fprintf(out, "=== %s (mode %04o)\n%s\n", f.Path, f.Mode, f.Body)
		}
		return 0
	}
	if err := os.MkdirAll(spec.BaseDir, 0o700); err != nil {
		fmt.Fprintf(errOut, "install: create %s: %v\n", spec.BaseDir, err)
		return 1
	}
	for _, f := range files {
		if err := os.MkdirAll(filepath.Dir(f.Path), 0o755); err != nil {
			fmt.Fprintf(errOut, "install: create %s: %v\n", filepath.Dir(f.Path), err)
			return 1
		}
		if err := os.WriteFile(f.Path, []byte(f.Body), f.Mode); err != nil {
			fmt.Fprintf(errOut, "install: write %s: %v\n", f.Path, err)
			return 1
		}
		// WriteFile applies the mode only when it creates the file; an upgrade over an existing
		// file would keep the old permissions, and the env file must be 0600 whoever owns the
		// previous copy.
		if err := os.Chmod(f.Path, f.Mode); err != nil {
			fmt.Fprintf(errOut, "install: chmod %s: %v\n", f.Path, err)
			return 1
		}
		fmt.Fprintf(out, "wrote %s\n", f.Path)
	}

	// Loading is the service manager's job and it is per-user: no sudo, no system unit.
	switch runtime.GOOS {
	case "darwin":
		plist := filepath.Join(home, "Library", "LaunchAgents", spec.Label+".plist")
		_ = exec.Command("launchctl", "unload", plist).Run() // a reload needs the unload; failure is fine on a first install
		if cmd := exec.Command("launchctl", "load", plist); cmd.Run() != nil {
			fmt.Fprintf(errOut, "install: launchctl load %s failed; load it by hand\n", plist)
			return 1
		}
	case "linux":
		if cmd := exec.Command("systemctl", "--user", "daemon-reload"); cmd.Run() != nil {
			fmt.Fprintf(errOut, "install: systemctl --user daemon-reload failed; run it by hand\n")
			return 1
		}
		if cmd := exec.Command("systemctl", "--user", "enable", "--now", spec.Label+".service"); cmd.Run() != nil {
			fmt.Fprintf(errOut, "install: systemctl --user enable --now failed; run it by hand\n")
			return 1
		}
	}
	fmt.Fprintf(out, "installed; the agent is running and will start at login\n")
	return 0
}
